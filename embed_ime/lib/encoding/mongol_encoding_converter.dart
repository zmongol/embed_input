/// Promote every U+E09C that starts a word to U+E096 (router.rs).
String _promoteWordInitialGO(String hub) {
  final chars = hub.runes.toList();
  final out = <int>[];
  for (var index = 0; index < chars.length; index++) {
    final c = chars[index];
    if (c == _legacyGOFina && !_joinedOnTheLeft(chars.sublist(0, index))) {
      out.add(_hubGOIsol);
    } else {
      out.add(c);
    }
  }
  return _fromRunes(out);
}

bool _joinedOnTheLeft(List<int> before) {
  for (var i = before.length - 1; i >= 0; i--) {
    final c = before[i];
    if (!_isTransparentMark(c)) return _joinsToTheRight(c);
  }
  return false;
}

bool _isTransparentMark(int c) =>
    (0x180b <= c && c <= 0x180d) || (0xe140 <= c && c <= 0xe144);

bool _joinsToTheRight(int c) =>
    zvvnmodCodes.contains(c) ||
    c == _hubGOIsol ||
    c == 0xe0e5 ||
    c == 0x180a ||
    c == 0x200d;

/// Decode a shape encoding to the hub (router.rs `translate_from`, shape arm).
/// [gapSpace]/[gapSpaced] is the encoding's punctuation gap: Z52 writes it
/// with U+202F, MenkShape with U+E263. The router's SoftBank-emoji restore
/// for MenkShape input is NOT ported: IME suggestions never contain
/// emoji-rewritten PUA, and the restore only affects chat-app input.
String _shapeToHub(
    String s, _ShapeRule rule, int gapSpace, List<(int, int)> gapSpaced) {
  final plain = _gapStrip(s, gapSpace, gapSpaced);
  final hub = _shapeTranslate(plain, rule);
  return _promoteWordInitialGO(hub.replaceAll(_unicodeNirugu, _hubNirugu));
}

/// Decode a letter encoding to the hub (router.rs `translate_from`, letter arm).
String _letterToHub(String s, _LetterFromRule rule) {
  final hub = _letterFromTranslate(s, rule);
  return _promoteWordInitialGO(hub.replaceAll(_unicodeNirugu, _hubNirugu));
}

/// Encode the hub to a letter encoding (router.rs `translate_to`, letter arm).
String _hubToLetter(String hub, _LetterToRule rule) {
  final h = hub.replaceAll(_unicodeNirugu, _hubNirugu);
  // The legacy tables predate E096; they write its ink for E09C.
  final legacy = h
      .replaceAll(_hubNirugu, _unicodeNirugu)
      .replaceAll(String.fromCharCode(_hubGOIsol),
          String.fromCharCode(_legacyGOFina));
  return _letterToTranslate(legacy, rule);
}

/// Encode the hub to a shape encoding (router.rs `translate_to`, shape arm).
String _hubToShape(String hub, _ShapeRule rule) {
  final h = hub.replaceAll(_unicodeNirugu, _hubNirugu);
  final legacy = h
      .replaceAll(_hubNirugu, _unicodeNirugu)
      .replaceAll(String.fromCharCode(_hubGOIsol),
          String.fromCharCode(_legacyGOFina));
  // The shape encodings have no NNBSP of their own: they spell a suffix
  // boundary with an ordinary space and always have.
  final flattened = legacy.replaceAll('\u{202f}', ' ');
  final shaped = _shapeTranslate(flattened, rule);
  return _gapInsert(shaped, 0x202f, z52GapSpaced);
}

