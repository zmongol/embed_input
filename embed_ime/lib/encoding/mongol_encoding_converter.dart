// Shape translator (shape/translator.rs)
// ---------------------------------------------------------------------------

String _shapeTranslate(String s, _ShapeRule rule) {
  if (_isBlank(s)) return '';
  final chars = [...s.runes, _sentinel];

  var word = _ShapeWord();
  var fragment = _ShapeFragment();
  final builder = StringBuffer();
  fragment.head = _CharType.other;

  var i = 0;
  while (i < chars.length) {
    final c = chars[i];
    if (rule.isTranslateCodePoint(c)) {
      fragment.push(c);
      // chars[i + 1] is always in bounds: the last char is the sentinel
      // (never a translate code point), so this branch is never entered
      // when i == len - 1.
      fragment.tail = rule.getCharType(chars[i + 1]);
      if (rule.contains(fragment)) {
        i++;
        continue; // greedy extend
      }
      fragment.pop();
      fragment.tail = rule.getCharType(c);
      if (fragment.isBlank) {
        // Passthrough: `c` is in this encoding's range but unmappable even
        // alone — emit it verbatim instead of erroring. Flush the pending
        // word first so output stays in order.
        if (word.isNotBlank) {
          _translateShapeWord(builder, word, rule);
          word = _ShapeWord();
        }
        builder.writeCharCode(c);
        fragment = _ShapeFragment();
        fragment.head = _CharType.other;
        i++;
        continue;
      }
      word.add(fragment);
      fragment = _ShapeFragment();
      // i >= 1 here: at i == 0 the fragment becomes blank above.
      fragment.head = rule.getCharType(chars[i - 1]);
      continue; // reprocess c
    } else {
      if (fragment.isNotBlank) {
        fragment.tail = _CharType.other;
        word.add(fragment);
        fragment = _ShapeFragment();
        fragment.head = _CharType.other;
      }
      if (word.isNotBlank) {
        _translateShapeWord(builder, word, rule);
        word = _ShapeWord();
      }
      builder.writeCharCode(c);
    }
    i++;
  }
  final out = builder.toString();
  return out.substring(0, out.length - 1); // strip the sentinel
}

void _translateShapeWord(
    StringBuffer builder, _ShapeWord word, _ShapeRule rule) {
  final pre = <int>[];
  for (final fragment in word.fragments) {
    final mapped = rule.getMapperCode(pre, fragment);
    if (mapped == null) {
      throw MongolConvertException(
          'not found in mapper: ${fragment.key}');
    }
    builder.write(mapped);
    pre.addAll(fragment.content);
  }
}

// ---------------------------------------------------------------------------
// Letter rules (letter/rule.rs, letter/menk.rs)
// ---------------------------------------------------------------------------

abstract class _LetterFromRule {
  String? getMapperCode(
      List<int> pre, List<int> suf, String key, _Nature nature);
  bool contains(String key);
  _Nature getCodeNature(int c);
  bool isTranslateCodePoint(int c);
  bool isWordCodePoint(int c);
}

abstract class _LetterToRule {
  void getMapperCode(StringBuffer builder, _ShapeWord word);
  bool contains(String key);
  bool isTranslateCodePoint(int c);
}

// FromMenkLetterCodeMapper.doubleIEhishig — NOTE: lacks U+1822 (unlike
// Delehi's set) (letter/menk.rs).
const Set<int> _doubleIEhshig = {0x1820, 0x1821, 0x1823, 0x1824};

class _MenkLetterFromRule implements _LetterFromRule {
  @override
  String? getMapperCode(
      List<int> pre, List<int> suf, String key, _Nature nature) {
    if (_trimSpaces(key) == '\u{180a}') return '\u{180a}';
    final devsger = _resolveDevsgerI(pre, key);
    if (devsger != null) return devsger;
    final w = _resolveW(pre, key);
    if (w != null) return w;
    final t = _resolveT(suf, key);
    if (t != null) return t;
    final g = _resolveG(pre, suf, key, nature);
    if (g != null) return g;
    final mapped = fromMenkLetter[key];
    if (mapped != null) return mapped;
    switch (nature) {
      case _Nature.chagh:
        return fromMenkLetterChagh[key];
      case _Nature.hundii:
        return fromMenkLetterHundii[key];
      case _Nature.saarmag:
        return fromMenkLetterSaarmag[key];
    }
  }

  @override
  bool contains(String key) =>
      fromMenkLetter.containsKey(key) ||
      fromMenkLetterChagh.containsKey(key);

  @override
  _Nature getCodeNature(int c) => _getCodeNature(c);

  @override
  bool isTranslateCodePoint(int c) =>
      _isNormalLetter(c) ||
      _isFreeVariationSelector(c) ||
      _isVowelSeparator(c) ||
      c == _wordConnector ||
      _otherMongolianCode(c);

  @override
  bool isWordCodePoint(int c) =>
      _isNormalLetter(c) ||
      _isFreeVariationSelector(c) ||
      _isVowelSeparator(c) ||
      _otherMongolianCode(c);
}

String? _resolveDevsgerI(List<int> pre, String s) {
  if (s != '\u{1836}' && s != '\u{1822}') return null;
  if (pre.isEmpty) return null;
  final c = pre.last;
  if (s == '\u{1822}' && (c == 0x1822 || c == 0x1836) && pre.length > 2) {
    final pre2 = pre[pre.length - 2];
    if (_doubleIEhshig.contains(pre2)) return '';
  }
  if (_doubleIEhshig.contains(c)) return '\u{e006}\u{e006}';
  return null;
}

String? _resolveW(List<int> pre, String s) {
  if (!s.contains('\u{1838}')) return null;
  if (pre.isEmpty) return null;
  final c = pre.last;
  if (_isEhshig(c)) return fromMenkLetterWWithEhshig[s];
  return null;
}

String? _resolveT(List<int> suf, String s) {
  if (s == '\u{1832}' && suf.isNotEmpty && _isGiiguulegch(suf[0])) {
    return '\u{e043}';
  }
  return null;
}

String? _resolveG(List<int> pre, List<int> suf, String s, _Nature nature) {
  if (s == '\u{182d}' && suf.isNotEmpty && _isGiiguulegch(suf[0])) {
    // GA after ANG ("ngg", e.g. U+1820 U+1829 U+182D ... "England"): the GA
    // keeps its hook form (U+E031) in both natures. The masculine
    // double-tooth form (U+E005 U+E005) applies to GA after other letters
    // only.
    if (_precededByAng(pre)) return '\u{e031}';
    return nature == _Nature.chagh ? '\u{e005}\u{e005}' : '\u{e031}';
  }
  return null;
}

/// True when the letter immediately before the current fragment is ANG
/// (U+1829), ignoring any free variation selectors in between.
bool _precededByAng(List<int> pre) {
  for (var i = pre.length - 1; i >= 0; i--) {
    final c = pre[i];
    if (!_isFreeVariationSelector(c)) return c == 0x1829;
  }
  return false;
}

class _MenkLetterToRule implements _LetterToRule {
  @override
  void getMapperCode(StringBuffer builder, _ShapeWord word) {
    var s = '';
    var ue031 = false;
    for (final fragment in word.fragments) {
      final key = fragment.key;
      String? s1 = _getMenk(s, key, word.nature);

      if (key == '\u{e031}') {
        ue031 = true;
        if (s.endsWith('\u{180d}\u{1822}')) {
          s = s.substring(0, s.length - 2) + '\u{1822}';
        }
      }
      if (ue031) {
        if (s1 != null && s1.contains('\u{180d}\u{1822}')) {
          ue031 = false;
          s1 = s1.replaceAll('\u{180d}\u{1822}', '\u{1822}');
        }
      }

      if (s1 == null) {
        throw MongolConvertException('not found in mapper: $key');
      }
      s = _concatAnd202f(s, s1);
    }
    if (s.startsWith('\u{202f}') && _endsWithBoundary(builder.toString())) {
      final b = builder.toString();
      builder.clear();
      builder.write(b.substring(0, b.length - 1));
    }
    builder.write(s);
  }

  @override
  bool contains(String key) =>
      toMenkLetterChagh.containsKey(key) || toMenkLetter.containsKey(key);

  @override
  bool isTranslateCodePoint(int c) => zvvnmodCodes.contains(c);
}

// Java MenkTranslateRuleTo.get: resolveUe00c, then resolveSingleGiiAndUe011,
// then the chagh/hundii table with a fallback to the base table when the
// nature table is empty/absent.
String? _getMenk(String pre, String s, _Nature nature) {
  final ue00c = _resolveUe00cMenk(pre, s, nature);
  if (ue00c != null) return ue00c;
  final gii = _resolveSingleGiiAndUe011(pre, s);
  if (gii != null) return gii;
  final m = nature == _Nature.chagh
      ? toMenkLetterChagh[s]
      : toMenkLetterHundii[s];
  if (m != null && m.isNotEmpty) return m;
  return toMenkLetter[s];
}

String? _resolveUe00cMenk(String pre, String s, _Nature nature) {
  if (s != '\u{e00c}') return null;
  final chaghOrHundii =
      nature == _Nature.chagh ? '\u{1820}' : '\u{1821}';
  if (pre.isEmpty) return chaghOrHundii;
  final last = pre.runes.last;
  if (_isTraditionalEhshig(last)) return '\u{1828}';
  return chaghOrHundii;
}

String? _resolveSingleGiiAndUe011(String pre, String s) {
  if (s != '\u{e011}' || pre.isEmpty) return null;
  if (pre.runes.length == 1) {
    final ch = pre.runes.first;
    if (_isGiiguulegch(ch)) {
      if (0x1832 <= ch && ch <= 0x1834) return '\u{1824}';
      return '\u{1824}\u{180b}';
    }
  }
  return null;
}

String _concatAnd202f(String s0, String s1) {
  if (s1.startsWith('\u{202f}') && _endsWithBoundary(s0)) {
    return s0.substring(0, s0.length - 1) + s1;
  }
  return s0 + s1;
}

// ---------------------------------------------------------------------------
// Letter translators (letter/from_translator.rs, letter/to_translator.rs)
// ---------------------------------------------------------------------------

_CharType _unicodeType(_LetterFromRule rule, int c) =>
    rule.isWordCodePoint(c) ? _CharType.mongolian : _CharType.other;

String _letterFromTranslate(String s, _LetterFromRule rule) {
  if (_isBlank(s)) return '';
  final chars = [...s.runes, _sentinel];

  final builder = StringBuffer();
  var fragment = _LetterFragment();
  var word = _LetterWord();
  fragment.head = _CharType.other;

  var i = 0;
  while (i < chars.length) {
    final c = chars[i];
    if (rule.isWordCodePoint(c)) {
      fragment.push(c);
      fragment.tail = _unicodeType(rule, chars[i + 1]);
      if (rule.contains(fragment.key)) {
        fragment.setNature(rule.getCodeNature(c));
        i++;
        continue;
      }
      fragment.pop();
      fragment.tail = _unicodeType(rule, c);
      if (fragment.isBlank) {
        // Passthrough: in-range but unmappable -> emit verbatim.
        if (word.isNotBlank) {
          _translateLetterWord(builder, word, rule);
          word = _LetterWord();
        }
        builder.writeCharCode(c);
        fragment = _LetterFragment();
        fragment.head = _CharType.other;
        i++;
        continue;
      }
      word.add(fragment);
      fragment = _LetterFragment();
      fragment.head = _unicodeType(rule, chars[i - 1]);
      continue; // reprocess c
    } else {
      if (fragment.isNotBlank) {
        fragment.tail = _CharType.other;
        word.add(fragment);
        fragment = _LetterFragment();
        fragment.head = _CharType.other;
      }
      if (word.isNotBlank) {
        _translateLetterWord(builder, word, rule);
        word = _LetterWord();
      }
      if (rule.isTranslateCodePoint(c)) {
        fragment.push(c);
      } else {
        builder.writeCharCode(c);
      }
    }
    i++;
  }
  final out = builder.toString();
  return out.substring(0, out.length - 1); // strip the sentinel
}

void _translateLetterWord(
    StringBuffer builder, _LetterWord word, _LetterFromRule rule) {
  word.removeInvalidCodePointFromEnd();
  final wordNature = word.nature;
  final n = word.fragments.length;
  final pre = <int>[];
  for (var idx = 0; idx < n; idx++) {
    final wf = word.fragments[idx];
    final nature =
        wf.nature == _Nature.saarmag ? wordNature : wf.nature;
    final suf =
        idx + 1 < n ? word.fragments[idx + 1].content : const <int>[];
    final key = wf.key;
    final mapped = rule.getMapperCode(pre, suf, key, nature);
    if (mapped == null) {
      throw MongolConvertException('not found in mapper: $key');
    }
    _pushMapped(builder, key, mapped);
    pre.addAll(wf.content);
  }
}

/// Emit one mapped fragment, restoring the suffix boundary the tables
/// flatten (letter/from_translator.rs): a key carrying the word connector
/// puts that boundary at the head of its value as a leading space, and it
/// goes back to NNBSP here.
void _pushMapped(StringBuffer builder, String key, String mapped) {
  if (key.contains('\u{202f}')) {
    if (mapped.startsWith(' ')) {
      builder.writeCharCode(_wordConnector);
      builder.write(mapped.substring(1));
      return;
    }
  }
  builder.write(mapped);
}

String _letterToTranslate(String s, _LetterToRule rule) {
  if (_isBlank(s)) return '';
  final chars = [...s.runes, _sentinel];

  final builder = StringBuffer();
  var fragment = _ShapeFragment();
  var word = _ShapeWord();

  for (final c in chars) {
    if (rule.isTranslateCodePoint(c)) {
      fragment.push(c);
      if (rule.contains(fragment.key)) {
        continue;
      }
      fragment.pop();
      if (fragment.isBlank) {
        // Passthrough: in-range but unmappable -> emit verbatim.
        if (word.isNotBlank) {
          rule.getMapperCode(builder, word);
          word = _ShapeWord();
        }
        builder.writeCharCode(c);
        fragment = _ShapeFragment();
        continue;
      }
      word.add(fragment);
      fragment = _ShapeFragment();
      fragment.push(c);
    } else {
      if (fragment.isNotBlank) {
        word.add(fragment);
        fragment = _ShapeFragment();
      }
      if (word.isNotBlank) {
        rule.getMapperCode(builder, word);
        word = _ShapeWord();
      }
      builder.writeCharCode(c);
    }
  }
  final out = builder.toString();
  return out.substring(0, out.length - 1); // strip the sentinel
}

// ---------------------------------------------------------------------------
// Punctuation gap (shape/punctuation_gap.rs) — Z52 only
// ---------------------------------------------------------------------------

/// The side of a mark that carries the gap: 0 = before, 1 = after, 2 = both.
int? _gapSide(List<(int, int)> spaced, int c) {
  for (final entry in spaced) {
    if (entry.$1 == c) return entry.$2;
  }
  return null;
}

bool _isWhitespace(int c) =>
    (0x09 <= c && c <= 0x0d) ||
    c == 0x20 ||
    c == 0x85 ||
    c == 0xa0 ||
    c == 0x1680 ||
    (0x2000 <= c && c <= 0x200a) ||
    c == 0x2028 ||
    c == 0x2029 ||
    c == 0x202f ||
    c == 0x205f ||
    c == 0x3000;

/// Take the gap back out, so it does not reach the hub.
String _gapStrip(String text, int space, List<(int, int)> spaced) {
  final chars = text.runes.toList();
  final out = <int>[];
  var skipNext = false;
  for (var index = 0; index < chars.length; index++) {
    if (skipNext) {
      skipNext = false;
      continue;
    }
    final c = chars[index];
    if (c == space &&
        index + 1 < chars.length &&
        (_gapSide(spaced, chars[index + 1]) == 0 ||
            _gapSide(spaced, chars[index + 1]) == 2)) {
      continue;
    }
    out.add(c);
    final side = _gapSide(spaced, c);
    if ((side == 1 || side == 2) &&
        index + 1 < chars.length &&
        chars[index + 1] == space) {
      skipNext = true;
    }
  }
  return _fromRunes(out);
}

/// Write the gap into shape text.
String _gapInsert(String text, int space, List<(int, int)> spaced) {
  final chars = text.runes.toList();
  final out = <int>[];
  for (var index = 0; index < chars.length; index++) {
    final c = chars[index];
    final side = _gapSide(spaced, c);
    if (side == null) {
      out.add(c);
      continue;
    }
    if (side == 0 || side == 2) {
      if (out.isNotEmpty) {
        final previous = out.last;
        if (previous == 0x20) {
          out.removeLast();
          out.add(space);
        } else if (previous == space || _isWhitespace(previous)) {
          // already separated
        } else {
          out.add(space);
        }
      }
    }
    out.add(c);
    if (side == 1 || side == 2) {
      if (index + 1 < chars.length) {
        final next = chars[index + 1];
        if (next == 0x20) {
          out.add(space);
        } else if (next == space || _isWhitespace(next)) {
          // already separated
        } else {
          out.add(space);
        }
      }
    }
  }
  // An ordinary space now sitting right after a gap is the one it replaced.
  final collapsed = <int>[];
  int? previous;
  for (final c in out) {
    if (c == 0x20 && previous == space) continue;
    collapsed.add(c);
    previous = c;
  }
  return _fromRunes(collapsed);
}

