// Mongolian encoding converter for the Flutter IME (boundary conversion).
//
// A mechanical Dart port of the verified desktop converter (mongol-convert,
// `~/workspace/mongol-code_convert`, Rust) for the Z52 <-> MenkLetter and
// MenkShape -> Z52 / MenkLetter paths. The engines below are line-for-line
// transliterations of the Rust translators:
//
//   * ShapeTranslator      <- crates/mongol-convert/src/shape/translator.rs
//   * Z52From / Z52To      <- shape/z52_from.rs, shape/z52_to.rs
//   * MenkShapeFrom        <- shape/menk_from.rs
//   * LetterFromTranslator <- letter/from_translator.rs
//   * LetterToTranslator   <- letter/to_translator.rs
//   * MenkLetterFrom/To    <- letter/menk.rs
//   * hub routing          <- router.rs (translate_from / translate_to)
//
// The lookup tables live in mongol_encoding_tables.dart, generated by
// tools/generate_mongol_tables.py from the same Rust sources — no hand
// edits there. Conversion goes through the Zvvnmod hub (private-use
// shapes, U+E000..), exactly as in the desktop converter.
//
// All characters are handled as Unicode code points (int runes), never as
// UTF-16 code units: the hub can carry astral scalars (the Zvvnmod birgas
// U+11660..U+11663), and Dart string indexing would split them.
//
// Validation (see tools/mongol_convert_mirror.py, a Python transliteration
// of this file): the mirror reproduces the Rust binary on the trimmed
// 135,631-word lexicon with 0 diffs for Z52 -> MenkLetter. MenkLetter ->
// Z52 matches the binary exactly too; the binary itself differs from the
// lexicon on ~3% of words there (MenkLetter collapses final-form
// distinctions the table in the desktop Python tool closes — see the
// converter docs). The IME boundary only uses Z52 -> MenkLetter,
// MenkShape -> Z52 and MenkShape -> MenkLetter, so that gap never fires
// on the boundary path.
//
// A conversion that cannot be mapped (a gap in the tables) returns its
// input unchanged instead of dropping the suggestion: a candidate in the
// wrong encoding is visible, a missing candidate is not.

import 'mongol_encoding_tables.dart';

/// The Mongolian encodings the IME can emit at its boundary.
///
/// * [z52] — Z52 (Zcode), the native encoding of `ZcodeLayoutTextConverter`.
/// * [menkLetter] — MenkLetter (Unicode Mongolian letters), the interchange
///   spelling produced by mongol-convert's `menk_letter` target.
/// * [menkShape] — MenkShape (Menksoft private-use shapes), the native
///   encoding of `MenkLayoutConverter`.
enum MongolEncoding {
  z52,
  menkLetter,
  menkShape,
}

/// Thrown by the low-level translators when a fragment has no mapping.
/// The public [MongolEncodingConverter] methods catch it and return their
/// input unchanged.
class MongolConvertException implements Exception {
  MongolConvertException(this.message);
  final String message;
  @override
  String toString() => 'MongolConvertException: $message';
}

// ---------------------------------------------------------------------------
// Small helpers (strings.rs, letter/rule.rs, unicode/mgl.rs)
// ---------------------------------------------------------------------------

/// Java `Strings.isBlank`: empty, or every character is `<= U+0020`.
bool _isBlank(String s) => s.runes.every((c) => c <= 0x20);

String _fromRunes(List<int> runes) => String.fromCharCodes(runes);

/// Rust `str::trim_matches(' ')`: strip only U+0020 from both ends.
String _trimSpaces(String s) {
  final runes = s.runes.toList();
  var start = 0;
  var end = runes.length;
  while (start < end && runes[start] == 0x20) {
    start++;
  }
  while (end > start && runes[end - 1] == 0x20) {
    end--;
  }
  return String.fromCharCodes(runes.sublist(start, end));
}

/// The suffix boundary, as the Zvvnmod hub spells it (letter/rule.rs).
const int _wordConnector = 0x202f;

/// True when `s` already ends in a suffix boundary (letter/rule.rs).
bool _endsWithBoundary(String s) {
  if (s.isEmpty) return false;
  final last = s.runes.last;
  return last == 0x20 || last == _wordConnector;
}

/// U+180A (nirugu) as the legacy tables and the Unicode encodings spell it.
const String _unicodeNirugu = '\u{180a}';

/// The nirugu, as the Zvvnmod hub spells it (router.rs).
const String _hubNirugu = '\u{e0e5}';

/// The hub's word-initial G + O-final ligature, U+E096 (router.rs).
const int _hubGOIsol = 0xe096;

/// The medial ligature the legacy tables spell the whole word with.
const int _legacyGOFina = 0xe09c;

/// The segmenter sentinel (shape/translator.rs): forces a final flush and
/// is stripped at the end. It is not a translate code point for any rule.
const int _sentinel = 0xe666;

// --- unicode/mgl.rs (Mongolian Unicode block predicates) ---

bool _isChagh(int c) => c == 0x1820 || c == 0x1823 || c == 0x1824;

bool _isHundii(int c) => c == 0x1821 || c == 0x1825 || c == 0x1826;

bool _inEhshigSet(int c) =>
    c == 0x1820 ||
    c == 0x1821 ||
    c == 0x1822 ||
    c == 0x1823 ||
    c == 0x1824 ||
    c == 0x1825 ||
    c == 0x1826;

bool _isNormalLetter(int c) => 0x1820 <= c && c <= 0x183f;

bool _isFreeVariationSelector(int c) => 0x180b <= c && c <= 0x180d;

bool _isVowelSeparator(int c) => c == 0x180e;

bool _isEhshig(int c) => _inEhshigSet(c) || c == 0x1827;

bool _isTraditionalEhshig(int c) => _inEhshigSet(c);

bool _isGiiguulegch(int c) => 0x1828 <= c && c <= 0x1842;

bool _otherMongolianCode(int c) => c == 0x180a;

_Nature _getCodeNature(int c) =>
    _isChagh(c) ? _Nature.chagh : _isHundii(c) ? _Nature.hundii : _Nature.saarmag;

// ---------------------------------------------------------------------------
// Word models (word/char_type.rs, word/nature.rs, word/shape_word.rs,
// word/letter_word.rs)
// ---------------------------------------------------------------------------

enum _CharType { mongolian, other }

enum _Nature { chagh, hundii, saarmag }

class _ShapeFragment {
  _CharType? head;
  _CharType? tail;
  final List<int> content = [];

  bool get isBlank => content.isEmpty;
  bool get isNotBlank => content.isNotEmpty;

  void push(int c) => content.add(c);

  /// Java `pop`: the translators only call this on a non-empty fragment.
  void pop() => content.removeLast();

  /// Raw content joined, no padding. Java `getKey`.
  String get key => _fromRunes(content);

  /// Content with a leading/trailing U+0020 when head/tail is not
  /// Mongolian. Java `getLocateKey` (from-shape rules only).
  String get locateKey {
    if (content.isEmpty) return '';
    final sb = StringBuffer();
    if (head != _CharType.mongolian) sb.write(' ');
    sb.write(_fromRunes(content));
    if (tail != _CharType.mongolian) sb.write(' ');
    return sb.toString();
  }
}

class _ShapeWord {
  // Java ShapeWord defaults to CHAGH (vs LetterWord's SAARMAG).
  _Nature nature = _Nature.chagh;
  final List<_ShapeFragment> fragments = [];

  bool get isBlank => fragments.isEmpty;
  bool get isNotBlank => fragments.isNotEmpty;

  /// Java `add`: latches nature to HUNDII for three magic fragment keys.
  void add(_ShapeFragment fragment) {
    final k = fragment.key;
    if (k == '\u{e006}\u{e00d}' ||
        k == '\u{e031}' ||
        k == '\u{e006}\u{e006}\u{e00d}') {
      nature = _Nature.hundii;
    }
    fragments.add(fragment);
  }
}

class _LetterFragment {
  _CharType? head;
  _CharType? tail;
  final List<int> content = [];
  _Nature nature = _Nature.saarmag;

  /// Space-padded by head/tail context. Java `getKey` (the from-direction
  /// locate key — unlike ShapeWordFragment, this one IS padded).
  String get key {
    if (content.isEmpty) return '';
    final sb = StringBuffer();
    if (head != _CharType.mongolian) sb.write(' ');
    sb.write(_fromRunes(content));
    if (tail != _CharType.mongolian) sb.write(' ');
    return sb.toString();
  }

  /// Java `setNature`: one-way latch SAARMAG -> non-SAARMAG.
  void setNature(_Nature n) {
    if (nature == _Nature.saarmag && n != _Nature.saarmag) {
      nature = n;
    }
  }

  bool get isBlank => content.isEmpty;
  bool get isNotBlank => content.isNotEmpty;

  int get size => content.length;

  int? get lastChar => content.isEmpty ? null : content.last;

  void push(int c) => content.add(c);

  void pop() => content.removeLast();
}

class _LetterWord {
  _Nature nature = _Nature.saarmag;
  final List<_LetterFragment> fragments = [];

  bool get isBlank => fragments.isEmpty;
  bool get isNotBlank => fragments.isNotEmpty;

  /// Java `add`: latch the word nature from the first non-SAARMAG fragment.
  void add(_LetterFragment fragment) {
    if (nature == _Nature.saarmag && fragment.nature != _Nature.saarmag) {
      nature = fragment.nature;
    }
    fragments.add(fragment);
  }

  /// Java `removeInvalidCodePointFromEnd`: trim trailing single-char VS/FVS
  /// fragments that duplicate the preceding fragment's last char (and mark
  /// that fragment's tail OTHER).
  void removeInvalidCodePointFromEnd() {
    if (fragments.isEmpty) return;
    var i = fragments.length - 1;
    while (true) {
      if (i == 0) return;
      final frag = fragments[i];
      if (frag.size != 1) return;
      final ch = frag.content[0];
      if (!_isVowelSeparator(ch) && !_isFreeVariationSelector(ch)) return;
      final preLast = fragments[i - 1].lastChar;
      if (preLast == ch) {
        fragments.removeAt(i);
        fragments[i - 1].tail = _CharType.other;
      }
      i--;
    }
  }
}

// ---------------------------------------------------------------------------
// Shape rules (shape/rule.rs, shape/z52_from.rs, shape/z52_to.rs,
// shape/menk_from.rs)
// ---------------------------------------------------------------------------

abstract class _ShapeRule {
  bool isTranslateCodePoint(int c);
  bool contains(_ShapeFragment fragment);
  String? getMapperCode(List<int> pre, _ShapeFragment fragment);
  _CharType? getCharType(int c);
}

class _Z52FromRule implements _ShapeRule {
  @override
  bool isTranslateCodePoint(int c) =>
      z52Codes.contains(c) || z52CodePunctuations.contains(c);

  @override
  bool contains(_ShapeFragment fragment) =>
      fromZ52.containsKey(fragment.locateKey);

  @override
  String? getMapperCode(List<int> pre, _ShapeFragment fragment) =>
      fromZ52[fragment.locateKey];

  @override
  _CharType? getCharType(int c) =>
      z52Codes.contains(c) ? _CharType.mongolian : _CharType.other;
}

class _Z52ToRule implements _ShapeRule {
  @override
  bool isTranslateCodePoint(int c) =>
      zvvnmodCodes.contains(c) ||
      unicodeToZ52Punctuation.containsKey(String.fromCharCode(c));

  @override
  bool contains(_ShapeFragment fragment) =>
      _z52PunctuationForKey(fragment.key) != null ||
      toZ52.containsKey(fragment.key);

  @override
  String? getMapperCode(List<int> pre, _ShapeFragment fragment) =>
      _z52PunctuationForKey(fragment.key) ?? toZ52[fragment.key];

  @override
  _CharType? getCharType(int c) => null;
}

/// `z52_punctuation::get`: only a single-char key maps (tables/z52_punctuation.rs).
String? _z52PunctuationForKey(String key) {
  final runes = key.runes.toList();
  if (runes.length != 1) return null;
  return unicodeToZ52Punctuation[String.fromCharCode(runes[0])];
}

class _MenkShapeFromRule implements _ShapeRule {
  @override
  bool isTranslateCodePoint(int c) {
    if (menkShapeNotSupport.contains(c)) return false;
    return (0xe263 <= c && c <= 0xe34a) || (0xe234 <= c && c <= 0xe261);
  }

  @override
  bool contains(_ShapeFragment fragment) =>
      fromMenkShape.containsKey(fragment.locateKey);

  @override
  String? getMapperCode(List<int> pre, _ShapeFragment fragment) {
    if (fragment.content.length == 1) {
      final birga = menkShapeBirgaToZvvnmod[
          String.fromCharCode(fragment.content[0])];
      if (birga != null) return birga;
    }
    return fromMenkShape[fragment.locateKey];
  }

  @override
  _CharType? getCharType(int c) =>
      // Java isWordCodePoint: E264..=E34F
      (0xe264 <= c && c <= 0xe34f) ? _CharType.mongolian : _CharType.other;
}

