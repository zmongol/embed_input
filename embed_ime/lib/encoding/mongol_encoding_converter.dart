/// Converts IME suggestions between Mongolian encodings at the boundary.
///
/// The converter is stateless and safe to share. A conversion that cannot
/// be mapped returns its input unchanged (see the file header).
class MongolEncodingConverter {
  const MongolEncodingConverter();

  /// Shared instance for call sites that do not need their own.
  static const MongolEncodingConverter shared = MongolEncodingConverter();

  /// Z52 -> MenkLetter. The direction the Zcode package's boundary uses;
  /// validated with 0 diffs over the 135,631-word trimmed lexicon.
  String z52ToMenkLetter(String input) {
    if (_isBlank(input)) return input;
    try {
      final hub = _shapeToHub(input, _Z52FromRule(), 0x202f, z52GapSpaced);
      return _hubToLetter(hub, _MenkLetterToRule());
    } on MongolConvertException {
      return input;
    }
  }

  /// MenkLetter -> Z52. Matches the desktop converter exactly; the desktop
  /// converter itself differs from the lexicon on ~3% of words in this
  /// direction (MenkLetter collapses final-form distinctions). Not used by
  /// either IME package's boundary today.
  String menkLetterToZ52(String input) {
    if (_isBlank(input)) return input;
    try {
      final hub = _letterToHub(input, _MenkLetterFromRule());
      return _hubToShape(hub, _Z52ToRule());
    } on MongolConvertException {
      return input;
    }
  }

  /// MenkShape (Menksoft PUA, the Menk package's native encoding) -> Z52.
  /// The direction the Menk package's boundary uses when
  /// `outputEncoding` is [MongolEncoding.z52].
  String menkShapeToZ52(String input) {
    if (_isBlank(input)) return input;
    try {
      final hub =
          _shapeToHub(input, _MenkShapeFromRule(), 0xe263, menkShapeGapSpaced);
      return _hubToShape(hub, _Z52ToRule());
    } on MongolConvertException {
      return input;
    }
  }

  /// MenkShape (Menksoft PUA) -> MenkLetter. The direction the Menk
  /// package's boundary uses when `outputEncoding` is
  /// [MongolEncoding.menkLetter].
  String menkShapeToMenkLetter(String input) {
    if (_isBlank(input)) return input;
    try {
      final hub =
          _shapeToHub(input, _MenkShapeFromRule(), 0xe263, menkShapeGapSpaced);
      return _hubToLetter(hub, _MenkLetterToRule());
    } on MongolConvertException {
      return input;
    }
  }
}
