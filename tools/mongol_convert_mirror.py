"""Python mirror of embed_ime/lib/encoding/mongol_encoding_converter.dart.

Purpose: validate the Dart port on this VM, where no Dart/Flutter toolchain
exists. Every function below is a line-for-line transliteration of the Dart
source (same tables — loaded from mongol_encoding_tables.json, generated by
the same script that produced the Dart tables — same order of rules, same
indices). If this mirror disagrees with the Dart file, the Dart file wins
and this file must be re-transliterated.

Usage:
  python3 mongol_convert_mirror.py --validate
      Runs all validations against the Rust binary (ground truth) and the
      trimmed 135,631-word lexicon; prints diff counts.
  python3 mongol_convert_mirror.py z52 "ᢌᡭᡪᢊᡱᡱᡭᢐ"
      Convert one word: direction z52|menk|shape-z52|shape-menk.
"""
