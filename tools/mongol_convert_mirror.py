def z52_to_menk_letter(inp):
    if is_blank(inp):
        return inp
    hub = shape_to_hub(inp, Z52FromRule(), "\u202f", z52_gap_spaced)
    return hub_to_letter(hub, MenkLetterToRule())


def menk_letter_to_z52(inp):
    if is_blank(inp):
        return inp
    hub = letter_to_hub(inp, MenkLetterFromRule())
    return hub_to_shape(hub, Z52ToRule())


def menk_shape_to_z52(inp):
    if is_blank(inp):
        return inp
    hub = shape_to_hub(inp, MenkShapeFromRule(), "\ue263",
                        menk_shape_gap_spaced)
    return hub_to_shape(hub, Z52ToRule())


def menk_shape_to_menk_letter(inp):
    if is_blank(inp):
        return inp
    hub = shape_to_hub(inp, MenkShapeFromRule(), "\ue263",
                        menk_shape_gap_spaced)
    return hub_to_letter(hub, MenkLetterToRule())


BIN = os.path.expanduser(
    "~/workspace/mongol-code_convert/target/debug/mongol-convert")


def run_binary(text, frm, to):
    p = subprocess.run([BIN, "translate", "--from", frm, "--to", to],
                       input=text.encode("utf-8"), capture_output=True)
    assert p.returncode == 0, p.stderr.decode("utf-8", "replace")[:500]
    return p.stdout.decode("utf-8")


def load_lexicon():
    rows = []
    with open(os.path.expanduser(
            "~/workspace/mobile-lexicon/lexicon-top135k.tsv"),
            encoding="utf-8") as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) >= 4:
                rows.append((p[1], p[2]))
    return rows


def validate():
    rows = load_lexicon()
    print(f"lexicon rows: {len(rows)}")
    z52text = "\n".join(z for z, m in rows)
    menktext = "\n".join(m for z, m in rows)

    # 1. Z52 -> MenkLetter: mirror vs lexicon (must be 0) and vs binary.
    got = [z52_to_menk_letter(z) for z in (r[0] for r in rows)]
    d_lex = sum(1 for i, r in enumerate(rows) if got[i] != r[1])
    print(f"Z52->MenkLetter mirror vs lexicon diffs: {d_lex}")
    for i, r in enumerate(rows):
        if got[i] != r[1] and d_lex <= 10:
            print(f"  z52 {r[0]!r} lex {r[1]!r} mirror {got[i]!r}")
            if sum(1 for _ in range(1)) > 5:
                break
    bin_out = run_binary(z52text, "z52", "menk_letter").split("\n")
    d_bin = sum(1 for i in range(len(rows)) if got[i] != bin_out[i])
    print(f"Z52->MenkLetter mirror vs binary diffs: {d_bin}")

    # 2. MenkLetter -> Z52: mirror vs binary (must be 0); vs lexicon (known gap).
    got2 = [menk_letter_to_z52(m) for m in (r[1] for r in rows)]
    bin_out2 = run_binary(menktext, "menk_letter", "z52").split("\n")
    d_bin2 = sum(1 for i in range(len(rows)) if got2[i] != bin_out2[i])
    print(f"MenkLetter->Z52 mirror vs binary diffs: {d_bin2}")
    d_lex2 = sum(1 for i, r in enumerate(rows) if got2[i] != r[0])
    print(f"MenkLetter->Z52 mirror vs lexicon diffs: {d_lex2} "
          f"({100.0 * d_lex2 / len(rows):.2f}% — known converter gap)")

    # 3. MenkShape legs: binary-generated menk_shape corpus as input.
    shape_corpus = run_binary(z52text, "z52", "menk_shape").split("\n")
    assert len(shape_corpus) == len(rows)
    got3 = [menk_shape_to_z52(s) for s in shape_corpus]
    # mirror vs binary on the menk_shape corpus (single binary call)
    bin_out3 = run_binary("\n".join(shape_corpus), "menk_shape",
                          "z52").split("\n")
    d_bin3 = sum(1 for i in range(len(rows)) if got3[i] != bin_out3[i])
    print(f"MenkShape->Z52 mirror vs binary diffs: {d_bin3}")
    d_lex3 = sum(1 for i, r in enumerate(rows) if got3[i] != r[0])
    print(f"MenkShape->Z52 mirror vs lexicon diffs: {d_lex3}")
    got4 = [menk_shape_to_menk_letter(s) for s in shape_corpus]
    bin_out4 = run_binary("\n".join(shape_corpus), "menk_shape",
                          "menk_letter").split("\n")
    d_bin4 = sum(1 for i in range(len(rows)) if got4[i] != bin_out4[i])
    print(f"MenkShape->MenkLetter mirror vs binary diffs: {d_bin4}")
    d_lex4 = sum(1 for i, r in enumerate(rows) if got4[i] != r[1])
    print(f"MenkShape->MenkLetter mirror vs lexicon diffs: {d_lex4}")

    # 4. Round-trip + edge cases vs binary.
    edge = ["", "   ", "abc", "mongol", "ᢌᡭᡪᢊᡱᡱᡭᢐ",
            "ᢌᡭᡪᢊᡱᡱᡭᢐ ᢔᡪᢝᡨ", "ᢌᡭᡪᢊᡱᡱᡭᢐ\u184f",
            "ᢌᡭᡪᢊᡱᡱᡭᢐ\u202fᡬᡬᡧ", "ᠮᠣᠩᠭᠣᠯ",
            "ᠮᠣᠩᠭᠣᠯ ᠰᠠᠶᠢᠨ", "\u202fᠦᠨ", "ᠢ", "ᠠ", "ᠡ"]
    for txt in edge:
        for fn, frm, to in (
                (z52_to_menk_letter, "z52", "menk_letter"),
                (menk_letter_to_z52, "menk_letter", "z52")):
            try:
                m = fn(txt)
            except MongolConvertException as e:
                m = f"<ERR {e}>"
            b = run_binary(txt, frm, to)
            mark = "OK  " if m == b else "DIFF"
            if m != b:
                print(f"  {mark} {fn.__name__} {txt!r}: mirror {m!r} binary {b!r}")
    print("edge cases done (only diffs printed)")

    # 5. Battery words (Z52 -> MenkLetter) vs lexicon/dictionary forms.
    battery = {
        "ᢌᡭᡪᢊᡱᡱᡭᢐ": "ᠮᠣᠩᠭᠣᠯ",
        "ᢜᡪᡴᡭᡰᡨ": None, "ᡴᡭᢙᡭᡪᡪᢔᡪᡧ": None,
        "ᡴᡭᡬᢙᡭᢊᢔᡪᡧ": "ᠪᠦᠳ᠋ᠦᠭᠰᠡᠨ",
        "ᢘᡪᡪᡬᡨ": None, "ᢔᡪᢝᡨ": None,
    }
    for z52, expected in battery.items():
        got = z52_to_menk_letter(z52)
        b = run_binary(z52, "z52", "menk_letter")
        print(f"  battery {z52!r} -> mirror {got!r} binary {b!r}"
              + (f" expected {expected!r}" if expected else ""))


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "--validate":
        validate()
    elif len(sys.argv) >= 3:
        direction, text = sys.argv[1], sys.argv[2]
