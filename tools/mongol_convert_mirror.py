class Z52FromRule:
    def is_translate_code_point(self, c):
        return ord(c) in z52_codes or ord(c) in z52_code_punctuations

    def contains(self, fragment):
        return fragment.locate_key in from_z52

    def get_mapper_code(self, pre, fragment):
        return from_z52.get(fragment.locate_key)

    def get_char_type(self, c):
        return "mongolian" if ord(c) in z52_codes else "other"


class Z52ToRule:
    def is_translate_code_point(self, c):
        return ord(c) in zvvnmod_codes or c in unicode_to_z52_punctuation

    def contains(self, fragment):
        return (z52_punctuation_for_key(fragment.key) is not None
                or fragment.key in to_z52)

    def get_mapper_code(self, pre, fragment):
        p = z52_punctuation_for_key(fragment.key)
        return p if p is not None else to_z52.get(fragment.key)

    def get_char_type(self, c):
        return None


def z52_punctuation_for_key(key):
    if len(key) != 1:
        return None
    return unicode_to_z52_punctuation.get(key)


class MenkShapeFromRule:
    def is_translate_code_point(self, c):
        if ord(c) in menk_shape_not_support:
            return False
        return (0xE263 <= ord(c) <= 0xE34A) or (0xE234 <= ord(c) <= 0xE261)

    def contains(self, fragment):
        return fragment.locate_key in from_menk_shape

    def get_mapper_code(self, pre, fragment):
        if len(fragment.content) == 1:
            birga = menk_shape_birga_to_zvvnmod.get(fragment.content[0])
            if birga is not None:
                return birga
        return from_menk_shape.get(fragment.locate_key)

    def get_char_type(self, c):
        return "mongolian" if 0xE264 <= ord(c) <= 0xE34F else "other"


# --- shape translator ---
def shape_translate(s, rule):
    if is_blank(s):
        return ""
    chars = list(s) + [chr(SENTINEL)]
    word = ShapeWord()
    fragment = ShapeFragment()
    builder = []
    fragment.head = "other"
    i = 0
    while i < len(chars):
        c = chars[i]
        if rule.is_translate_code_point(c):
            fragment.push(c)
            fragment.tail = rule.get_char_type(chars[i + 1])
            if rule.contains(fragment):
                i += 1
                continue
            fragment.pop()
            fragment.tail = rule.get_char_type(c)
            if fragment.is_blank:
                if word.is_not_blank:
                    translate_shape_word(builder, word, rule)
                    word = ShapeWord()
                builder.append(c)
                fragment = ShapeFragment()
                fragment.head = "other"
                i += 1
                continue
            word.add(fragment)
            fragment = ShapeFragment()
            fragment.head = rule.get_char_type(chars[i - 1])
            continue
        else:
            if fragment.is_not_blank:
                fragment.tail = "other"
                word.add(fragment)
                fragment = ShapeFragment()
                fragment.head = "other"
            if word.is_not_blank:
                translate_shape_word(builder, word, rule)
                word = ShapeWord()
            builder.append(c)
        i += 1
    out = "".join(builder)
    return out[:-1]  # strip the sentinel


def translate_shape_word(builder, word, rule):
    pre = []
    for fragment in word.fragments:
        mapped = rule.get_mapper_code(pre, fragment)
        if mapped is None:
            raise MongolConvertException(
                "not found in mapper: " + fragment.key)
        builder.append(mapped)
        pre.extend(fragment.content)


# --- letter rules ---
DOUBLE_I_EHSHIG = {"\u1820", "\u1821", "\u1823", "\u1824"}


class MenkLetterFromRule:
    def get_mapper_code(self, pre, suf, key, nature):
        if trim_spaces(key) == "\u180a":
            return "\u180a"
        r = resolve_devsger_i(pre, key)
        if r is not None:
            return r
        r = resolve_w(pre, key)
        if r is not None:
            return r
        r = resolve_t(suf, key)
        if r is not None:
            return r
        r = resolve_g(pre, suf, key, nature)
        if r is not None:
            return r
        if key in from_menk_letter:
            return from_menk_letter[key]
        if nature == CHAGH:
            return from_menk_letter_chagh.get(key)
        if nature == HUNDII:
            return from_menk_letter_hundii.get(key)
        return from_menk_letter_saarmag.get(key)

    def contains(self, key):
        return key in from_menk_letter or key in from_menk_letter_chagh

    def get_code_nature(self, c):
        return get_code_nature(c)

    def is_translate_code_point(self, c):
        return (is_normal_letter(c) or is_fvs(c) or is_vs(c)
                or c == WORD_CONNECTOR or other_mongolian_code(c))

    def is_word_code_point(self, c):
        return (is_normal_letter(c) or is_fvs(c) or is_vs(c)
                or other_mongolian_code(c))


def resolve_devsger_i(pre, s):
    if s != "\u1836" and s != "\u1822":
        return None
    if not pre:
        return None
    c = pre[-1]
    if s == "\u1822" and c in ("\u1822", "\u1836") and len(pre) > 2:
        if pre[-2] in DOUBLE_I_EHSHIG:
            return ""
    if c in DOUBLE_I_EHSHIG:
        return "\ue006\ue006"
    return None


def resolve_w(pre, s):
    if "\u1838" not in s:
        return None
    if not pre:
        return None
    c = pre[-1]
    if is_ehshig(c):
        return from_menk_letter_w_with_ehshig.get(s)
    return None


def resolve_t(suf, s):
    if s == "\u1832" and suf and is_giiguulegch(suf[0]):
        return "\ue043"
    return None


def resolve_g(pre, suf, s, nature):
    if s == "\u182d" and suf and is_giiguulegch(suf[0]):
        if preceded_by_ang(pre):
            return "\ue031"
        return "\ue005\ue005" if nature == CHAGH else "\ue031"
    return None


def preceded_by_ang(pre):
    for c in reversed(pre):
        if not is_fvs(c):
            return c == "\u1829"
    return False


class MenkLetterToRule:
    def get_mapper_code(self, builder, word):
        s = ""
        ue031 = False
        for fragment in word.fragments:
            key = fragment.key
            s1 = get_menk(s, key, word.nature)
            if key == "\ue031":
                ue031 = True
                if s.endswith("\u180d\u1822"):
                    s = s[:-2] + "\u1822"
            if ue031:
                if s1 is not None and "\u180d\u1822" in s1:
                    ue031 = False
                    s1 = s1.replace("\u180d\u1822", "\u1822")
            if s1 is None:
                raise MongolConvertException("not found in mapper: " + key)
            s = concat_and_202f(s, s1)
        if s.startswith(WORD_CONNECTOR) and ends_with_boundary("".join(builder)):
            builder.pop()
        builder.append(s)

    def contains(self, key):
        return key in to_menk_letter_chagh or key in to_menk_letter

    def is_translate_code_point(self, c):
        return ord(c) in zvvnmod_codes


def get_menk(pre, s, nature):
    r = resolve_ue00c_menk(pre, s, nature)
    if r is not None:
        return r
    r = resolve_single_gii_and_ue011(pre, s)
    if r is not None:
        return r
    m = (to_menk_letter_chagh.get(s) if nature == CHAGH
         else to_menk_letter_hundii.get(s))
    if m:
        return m
    return to_menk_letter.get(s)


def resolve_ue00c_menk(pre, s, nature):
    if s != "\ue00c":
        return None
    chagh_or_hundii = "\u1820" if nature == CHAGH else "\u1821"
    if not pre:
        return chagh_or_hundii
    if is_traditional_ehshig(pre[-1]):
        return "\u1828"
    return chagh_or_hundii


def resolve_single_gii_and_ue011(pre, s):
    if s != "\ue011" or not pre:
        return None
    if len(pre) == 1:
        ch = pre[0]
        if is_giiguulegch(ch):
            if 0x1832 <= ord(ch) <= 0x1834:
                return "\u1824"
            return "\u1824\u180b"
    return None


def concat_and_202f(s0, s1):
    if s1.startswith(WORD_CONNECTOR) and ends_with_boundary(s0):
        return s0[:-1] + s1
    return s0 + s1


# --- letter translators ---
def unicode_type(rule, c):
    return "mongolian" if rule.is_word_code_point(c) else "other"


def letter_from_translate(s, rule):
    if is_blank(s):
        return ""
    chars = list(s) + [chr(SENTINEL)]
    builder = []
    fragment = LetterFragment()
    word = LetterWord()
    fragment.head = "other"
    i = 0
    while i < len(chars):
        c = chars[i]
        if rule.is_word_code_point(c):
            fragment.push(c)
            fragment.tail = unicode_type(rule, chars[i + 1])
            if rule.contains(fragment.key):
                fragment.set_nature(rule.get_code_nature(c))
                i += 1
                continue
            fragment.pop()
            fragment.tail = unicode_type(rule, c)
            if fragment.is_blank:
                if word.is_not_blank:
                    translate_letter_word(builder, word, rule)
                    word = LetterWord()
                builder.append(c)
                fragment = LetterFragment()
                fragment.head = "other"
                i += 1
                continue
            word.add(fragment)
            fragment = LetterFragment()
            fragment.head = unicode_type(rule, chars[i - 1])
            continue
        else:
            if fragment.is_not_blank:
                fragment.tail = "other"
                word.add(fragment)
                fragment = LetterFragment()
                fragment.head = "other"
            if word.is_not_blank:
                translate_letter_word(builder, word, rule)
                word = LetterWord()
            if rule.is_translate_code_point(c):
                fragment.push(c)
            else:
                builder.append(c)
        i += 1
    out = "".join(builder)
    return out[:-1]


def translate_letter_word(builder, word, rule):
    word.remove_invalid_code_point_from_end()
    word_nature = word.nature
    n = len(word.fragments)
    pre = []
    for idx in range(n):
        wf = word.fragments[idx]
        nature = word_nature if wf.nature == SAARMAG else wf.nature
        suf = word.fragments[idx + 1].content if idx + 1 < n else []
        key = wf.key
        mapped = rule.get_mapper_code(pre, suf, key, nature)
        if mapped is None:
            raise MongolConvertException("not found in mapper: " + key)
        push_mapped(builder, key, mapped)
        pre.extend(wf.content)


def push_mapped(builder, key, mapped):
    if WORD_CONNECTOR in key and mapped.startswith(" "):
        builder.append(WORD_CONNECTOR)
        builder.append(mapped[1:])
        return
    builder.append(mapped)


def letter_to_translate(s, rule):
    if is_blank(s):
        return ""
    chars = list(s) + [chr(SENTINEL)]
    builder = []
    fragment = ShapeFragment()
    word = ShapeWord()
    for c in chars:
        if rule.is_translate_code_point(c):
            fragment.push(c)
            if rule.contains(fragment.key):
                continue
            fragment.pop()
            if fragment.is_blank:
                if word.is_not_blank:
                    rule.get_mapper_code(builder, word)
                    word = ShapeWord()
                builder.append(c)
                fragment = ShapeFragment()
                continue
            word.add(fragment)
            fragment = ShapeFragment()
            fragment.push(c)
        else:
            if fragment.is_not_blank:
                word.add(fragment)
                fragment = ShapeFragment()
            if word.is_not_blank:
                rule.get_mapper_code(builder, word)
                word = ShapeWord()
            builder.append(c)
    out = "".join(builder)
    return out[:-1]


# --- punctuation gap ---
def gap_side(spaced, c):
    for cp, side in spaced:
        if cp == ord(c):
            return side
    return None


def is_whitespace(c):
    o = ord(c)
    return ((0x09 <= o <= 0x0D) or o == 0x20 or o == 0x85 or o == 0xA0
            or o == 0x1680 or (0x2000 <= o <= 0x200A) or o == 0x2028
            or o == 0x2029 or o == 0x202F or o == 0x205F or o == 0x3000)


def gap_strip(text, space, spaced):
    chars = list(text)
    out = []
    skip_next = False
    for index, c in enumerate(chars):
        if skip_next:
            skip_next = False
            continue
        if (c == space and index + 1 < len(chars)
                and gap_side(spaced, chars[index + 1]) in (0, 2)):
            continue
        out.append(c)
        side = gap_side(spaced, c)
        if (side in (1, 2) and index + 1 < len(chars)
                and chars[index + 1] == space):
            skip_next = True
    return "".join(out)


def gap_insert(text, space, spaced):
    chars = list(text)
    out = []
    for index, c in enumerate(chars):
        side = gap_side(spaced, c)
        if side is None:
            out.append(c)
            continue
        if side in (0, 2):
            if out:
                prev = out[-1]
                if prev == " ":
                    out.pop()
                    out.append(space)
                elif prev == space or is_whitespace(prev):
                    pass
                else:
                    out.append(space)
        out.append(c)
        if side in (1, 2) and index + 1 < len(chars):
            nxt = chars[index + 1]
            if nxt == " ":
                out.append(space)
            elif nxt == space or is_whitespace(nxt):
                pass
            else:
                out.append(space)
    collapsed = []
    previous = None
    for c in out:
        if c == " " and previous == space:
            continue
        collapsed.append(c)
        previous = c
    return "".join(collapsed)


# --- hub routing ---
def promote_word_initial_g_o(hub):
    chars = list(hub)
    out = []
    for index, c in enumerate(chars):
        if ord(c) == LEGACY_G_O_FINA and not joined_on_the_left(chars[:index]):
            out.append(chr(HUB_G_O_ISOL))
        else:
            out.append(c)
    return "".join(out)


def joined_on_the_left(before):
    for c in reversed(before):
        if not is_transparent_mark(c):
            return joins_to_the_right(c)
    return False


def is_transparent_mark(c):
    return (0x180B <= ord(c) <= 0x180D) or (0xE140 <= ord(c) <= 0xE144)


def joins_to_the_right(c):
    return (ord(c) in zvvnmod_codes or ord(c) == HUB_G_O_ISOL
            or ord(c) == 0xE0E5 or c == "\u180a" or c == "\u200d")


def shape_to_hub(s, rule, gap_space, gap_spaced):
    plain = gap_strip(s, gap_space, gap_spaced)
    hub = shape_translate(plain, rule)
    return promote_word_initial_g_o(hub.replace(UNICODE_NIRUGU, HUB_NIRUGU))


def letter_to_hub(s, rule):
    hub = letter_from_translate(s, rule)
    return promote_word_initial_g_o(hub.replace(UNICODE_NIRUGU, HUB_NIRUGU))


def hub_to_letter(hub, rule):
    h = hub.replace(UNICODE_NIRUGU, HUB_NIRUGU)
    legacy = h.replace(HUB_NIRUGU, UNICODE_NIRUGU).replace(
        chr(HUB_G_O_ISOL), chr(LEGACY_G_O_FINA))
    return letter_to_translate(legacy, rule)


def hub_to_shape(hub, rule):
    h = hub.replace(UNICODE_NIRUGU, HUB_NIRUGU)
    legacy = h.replace(HUB_NIRUGU, UNICODE_NIRUGU).replace(
        chr(HUB_G_O_ISOL), chr(LEGACY_G_O_FINA))
    flattened = legacy.replace(WORD_CONNECTOR, " ")
    shaped = shape_translate(flattened, rule)
    return gap_insert(shaped, "\u202f", z52_gap_spaced)


