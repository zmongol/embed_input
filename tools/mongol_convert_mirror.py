WORD_CONNECTOR = "\u202f"
UNICODE_NIRUGU = "\u180a"
HUB_NIRUGU = "\ue0e5"
HUB_G_O_ISOL = 0xE096
LEGACY_G_O_FINA = 0xE09C
SENTINEL = 0xE666


class MongolConvertException(Exception):
    pass


def is_blank(s):
    return all(ord(c) <= 0x20 for c in s)


def trim_spaces(s):
    return s.strip(" ")


def ends_with_boundary(s):
    return bool(s) and s[-1] in (" ", WORD_CONNECTOR)


# --- mgl ---
def _is_chagh(c):
    return ord(c) in (0x1820, 0x1823, 0x1824)


def _is_hundii(c):
    return ord(c) in (0x1821, 0x1825, 0x1826)


def _in_ehshig_set(c):
    return ord(c) in (0x1820, 0x1821, 0x1822, 0x1823, 0x1824, 0x1825, 0x1826)


def is_normal_letter(c):
    return 0x1820 <= ord(c) <= 0x183F


def is_fvs(c):
    return 0x180B <= ord(c) <= 0x180D


def is_vs(c):
    return c == "\u180e"


def is_ehshig(c):
    return _in_ehshig_set(c) or c == "\u1827"


def is_traditional_ehshig(c):
    return _in_ehshig_set(c)


def is_giiguulegch(c):
    return 0x1828 <= ord(c) <= 0x1842


def other_mongolian_code(c):
    return c == "\u180a"


CHAGH, HUNDII, SAARMAG = "chagh", "hundii", "saarmag"


def get_code_nature(c):
    if _is_chagh(c):
        return CHAGH
    if _is_hundii(c):
        return HUNDII
    return SAARMAG


# --- word models ---
class ShapeFragment:
    def __init__(self):
        self.head = None  # 'mongolian' | 'other' | None
        self.tail = None
        self.content = []  # list of chars

    @property
    def is_blank(self):
        return not self.content

    @property
    def is_not_blank(self):
        return bool(self.content)

    def push(self, c):
        self.content.append(c)

    def pop(self):
        self.content.pop()

    @property
    def key(self):
        return "".join(self.content)

    @property
    def locate_key(self):
        if not self.content:
            return ""
        s = ""
        if self.head != "mongolian":
            s += " "
        s += "".join(self.content)
        if self.tail != "mongolian":
            s += " "
        return s


class ShapeWord:
    def __init__(self):
        self.nature = CHAGH
        self.fragments = []

    @property
    def is_blank(self):
        return not self.fragments

    @property
    def is_not_blank(self):
        return bool(self.fragments)

    def add(self, fragment):
        k = fragment.key
        if k in ("\ue006\ue00d", "\ue031", "\ue006\ue006\ue00d"):
            self.nature = HUNDII
        self.fragments.append(fragment)


class LetterFragment:
    def __init__(self):
        self.head = None
        self.tail = None
        self.content = []
        self.nature = SAARMAG

    @property
    def key(self):
        if not self.content:
            return ""
        s = ""
        if self.head != "mongolian":
            s += " "
        s += "".join(self.content)
        if self.tail != "mongolian":
            s += " "
        return s

    def set_nature(self, n):
        if self.nature == SAARMAG and n != SAARMAG:
            self.nature = n

    @property
    def is_blank(self):
        return not self.content

    @property
    def is_not_blank(self):
        return bool(self.content)

    @property
    def size(self):
        return len(self.content)

    @property
    def last_char(self):
        return self.content[-1] if self.content else None

    def push(self, c):
        self.content.append(c)

    def pop(self):
        self.content.pop()


class LetterWord:
    def __init__(self):
        self.nature = SAARMAG
        self.fragments = []

    @property
    def is_blank(self):
        return not self.fragments

    @property
    def is_not_blank(self):
        return bool(self.fragments)

    def add(self, fragment):
        if self.nature == SAARMAG and fragment.nature != SAARMAG:
            self.nature = fragment.nature
        self.fragments.append(fragment)

    def remove_invalid_code_point_from_end(self):
        if not self.fragments:
            return
        i = len(self.fragments) - 1
        while True:
            if i == 0:
                return
            frag = self.fragments[i]
            if frag.size != 1:
                return
            ch = frag.content[0]
            if not is_vs(ch) and not is_fvs(ch):
                return
            pre_last = self.fragments[i - 1].last_char
            if pre_last == ch:
                del self.fragments[i]
                self.fragments[i - 1].tail = "other"
            i -= 1


